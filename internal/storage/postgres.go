//go:embed schema.sql
var schemaSQL string

// PostgresStore is the durable detection store. It owns a pgxpool.Pool and is
// safe for concurrent use.
type PostgresStore struct {
	pool *pgxpool.Pool
}

// NewPostgresStore parses dsn, opens a pool and verifies connectivity.
func NewPostgresStore(ctx context.Context, dsn string) (*PostgresStore, error) {
	cfg, err := pgxpool.ParseConfig(dsn)
	if err != nil {
		return nil, fmt.Errorf("storage: parse postgres dsn: %w", err)
	}
	cfg.MaxConns = 24
	cfg.MinConns = 2
	cfg.MaxConnLifetime = 30 * time.Minute
	cfg.MaxConnIdleTime = 5 * time.Minute
	pool, err := pgxpool.NewWithConfig(ctx, cfg)
	if err != nil {
		return nil, fmt.Errorf("storage: open postgres pool: %w", err)
	}
	pingCtx, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()
	if err := pool.Ping(pingCtx); err != nil {
		pool.Close()
		return nil, fmt.Errorf("storage: ping postgres: %w", err)
	}
	return &PostgresStore{pool: pool}, nil
}

// NewPostgresStoreFromPool wraps an existing pool (used by integration tests).
func NewPostgresStoreFromPool(pool *pgxpool.Pool) *PostgresStore {
	return &PostgresStore{pool: pool}
}

// Pool exposes the underlying pool for health checks and tests.
func (s *PostgresStore) Pool() *pgxpool.Pool { return s.pool }

// Ping verifies the database is reachable.
func (s *PostgresStore) Ping(ctx context.Context) error { return s.pool.Ping(ctx) }

// Migrate applies schema.sql using the simple protocol (the schema contains
// multiple statements and a dollar-quoted function) and pre-creates partitions
// for yesterday, today and tomorrow.
func (s *PostgresStore) Migrate(ctx context.Context) error {
	conn, err := s.pool.Acquire(ctx)
	if err != nil {
		return fmt.Errorf("storage: acquire for migrate: %w", err)
	}
	defer conn.Release()
	mrr := conn.Conn().PgConn().Exec(ctx, schemaSQL)
	if _, err := mrr.ReadAll(); err != nil {
		return fmt.Errorf("storage: apply schema: %w", err)
	}
	today := time.Now().UTC().Truncate(24 * time.Hour)
	for _, day := range []time.Time{today.AddDate(0, 0, -1), today, today.AddDate(0, 0, 1)} {
		if err := s.EnsurePartition(ctx, day); err != nil {
			return err
		}
	}
	return nil
}

// EnsurePartition idempotently creates the daily partition (and its indexes)
// covering day. Concurrent callers may both attempt the DDL; the loser's
// duplicate_object error is treated as success.
func (s *PostgresStore) EnsurePartition(ctx context.Context, day time.Time) error {
	d := day.UTC().Format("2006-01-02")
	if _, err := s.pool.Exec(ctx, "SELECT evg_ensure_partition($1::date)", d); err != nil {
		var pgErr *pgconn.PgError
		if errors.As(err, &pgErr) && (pgErr.Code == "42P07" || pgErr.Code == "23505" || pgErr.Code == "42710") {
			return nil
		}
		return fmt.Errorf("storage: ensure partition %s: %w", d, err)
	}
	return nil
}

// InsertDetections writes dets in one COPY batch. IDs are generated by the
// database identity column.
func (s *PostgresStore) InsertDetections(ctx context.Context, dets []Detection) error {
	if len(dets) == 0 {
		return nil
	}
	rows := make([][]any, len(dets))
	for i, d := range dets {
		rows[i] = []any{d.DeviceID, d.FrameID, d.CapturedAt, d.Label, float32(d.Confidence), d.X, d.Y, d.W, d.H}
	}
	_, err := s.pool.CopyFrom(ctx,
		pgx.Identifier{"detections"},
		[]string{"device_id", "frame_id", "captured_at", "label", "confidence", "x", "y", "w", "h"},
		pgx.CopyFromRows(rows),
	)
	if err != nil {
		return fmt.Errorf("storage: copy detections: %w", err)
	}
	return nil
}

const detectionColumns = `id, device_id, frame_id, captured_at, label, confidence, x, y, w, h`

// QueryByDevice implements DetectionStore. It returns newest-first rows in
// [from, to), capped at limit (default 100, max 5000).
func (s *PostgresStore) QueryByDevice(ctx context.Context, deviceID string, from, to time.Time, limit int) ([]Detection, error) {
	if !from.Before(to) {
		return nil, ErrInvalidRange
	}
	limit = clampLimit(limit)
	rows, err := s.pool.Query(ctx,
		`SELECT `+detectionColumns+` FROM detections
		 WHERE device_id = $1 AND captured_at >= $2 AND captured_at < $3
		 ORDER BY captured_at DESC, id DESC LIMIT $4`,
		deviceID, from, to, limit)
	if err != nil {
		return nil, fmt.Errorf("storage: query by device: %w", err)
	}
	defer rows.Close()
	return scanDetections(rows)
}

// QueryByLabel implements DetectionStore. It returns newest-first rows in
// [from, to), capped at limit (default 100, max 5000).
func (s *PostgresStore) QueryByLabel(ctx context.Context, label string, from, to time.Time, limit int) ([]Detection, error) {
	if !from.Before(to) {
		return nil, ErrInvalidRange
	}
	limit = clampLimit(limit)
	rows, err := s.pool.Query(ctx,
		`SELECT `+detectionColumns+` FROM detections
		 WHERE label = $1 AND captured_at >= $2 AND captured_at < $3
		 ORDER BY captured_at DESC, id DESC LIMIT $4`,
		label, from, to, limit)
	if err != nil {
		return nil, fmt.Errorf("storage: query by label: %w", err)
	}
	defer rows.Close()
	return scanDetections(rows)
}

func scanDetections(rows pgx.Rows) ([]Detection, error) {
	out := make([]Detection, 0, 64)
	for rows.Next() {
		var d Detection
		var conf float32
		if err := rows.Scan(&d.ID, &d.DeviceID, &d.FrameID, &d.CapturedAt, &d.Label, &conf, &d.X, &d.Y, &d.W, &d.H); err != nil {
			return nil, fmt.Errorf("storage: scan detection: %w", err)
		}
		d.Confidence = float64(conf)
		out = append(out, d)
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("storage: iterate detections: %w", err)
	}
	return out, nil
}

// RegisterDevice upserts a device row. created_at is preserved on conflict and
// last_seen_at never moves backwards.
func (s *PostgresStore) RegisterDevice(ctx context.Context, d Device) error {
	if d.CreatedAt.IsZero() {
		d.CreatedAt = time.Now().UTC()
	}
	if d.LastSeenAt.IsZero() {
		d.LastSeenAt = d.CreatedAt
	}
	if d.Status == "" {
		d.Status = "active"
	}
	_, err := s.pool.Exec(ctx, `
		INSERT INTO devices (device_id, site_id, token_hash, status, created_at, last_seen_at)
		VALUES ($1, $2, $3, $4, $5, $6)
		ON CONFLICT (device_id) DO UPDATE SET
			site_id      = EXCLUDED.site_id,
			token_hash   = EXCLUDED.token_hash,
			status       = EXCLUDED.status,
			last_seen_at = GREATEST(devices.last_seen_at, EXCLUDED.last_seen_at)`,
		d.DeviceID, d.SiteID, d.TokenHash, d.Status, d.CreatedAt, d.LastSeenAt)
	if err != nil {
		return fmt.Errorf("storage: register device: %w", err)
	}
	return nil
}

// GetDevice reads a device row, returning ErrNotFound when absent.
func (s *PostgresStore) GetDevice(ctx context.Context, deviceID string) (Device, error) {
	var d Device
	err := s.pool.QueryRow(ctx,
		`SELECT device_id, site_id, token_hash, status, created_at, last_seen_at
		 FROM devices WHERE device_id = $1`, deviceID).
		Scan(&d.DeviceID, &d.SiteID, &d.TokenHash, &d.Status, &d.CreatedAt, &d.LastSeenAt)
	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return Device{}, ErrNotFound
		}
		return Device{}, fmt.Errorf("storage: get device: %w", err)
	}
	return d, nil
}

// TouchDevice updates last_seen_at, returning ErrNotFound for unknown devices.
func (s *PostgresStore) TouchDevice(ctx context.Context, deviceID string, at time.Time) error {
	tag, err := s.pool.Exec(ctx, `UPDATE devices SET last_seen_at = $2 WHERE device_id = $1`, deviceID, at)
	if err != nil {
		return fmt.Errorf("storage: touch device: %w", err)
	}
	if tag.RowsAffected() == 0 {
		return ErrNotFound
	}
	return nil
}

// Close releases the pool. It implements io.Closer.
func (s *PostgresStore) Close() error {
	s.pool.Close()
	return nil
}

func clampLimit(limit int) int {
	if limit <= 0 {
		return 100
	}
	if limit > 5000 {
		return 5000
	}
	return limit
}
